// Runs after `next build`. Writes out/sw.js, a service worker that precaches
// every file of the static export so the whole app works offline.
//
// The cache name includes a hash of the build, so each deploy installs a
// fresh cache. The new version waits until the user taps "Update ready"
// (or closes the app), so a running workout is never swapped mid-session.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve("out");
const SKIP = new Set(["sw.js"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => {
      const full = path.join(dir, e.name);
      return e.isDirectory() ? walk(full) : [full];
    }),
  );
  return files.flat();
}

const files = (await walk(OUT))
  .map((f) => path.relative(OUT, f).split(path.sep).join("/"))
  .filter((f) => !SKIP.has(f) && !f.endsWith(".map"))
  .sort();

const hash = createHash("sha256");
for (const f of files) {
  hash.update(f);
  hash.update(await readFile(path.join(OUT, f)));
}
const version = hash.digest("hex").slice(0, 12);

// [url to fetch, cache key]. HTML pages are keyed by their clean URL
// ("train/index.html" -> "/train/") so navigations match directly.
const entries = files.map((f) => {
  const url = "/" + f;
  if (f === "index.html") return [url, "/"];
  if (f.endsWith("/index.html")) return [url, "/" + f.slice(0, -"index.html".length)];
  return [url, url];
});

const sw = `/* Generated by scripts/generate-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = "dialed-" + VERSION;
const ENTRIES = ${JSON.stringify(entries)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await Promise.all(
        ENTRIES.map(async ([url, key]) => {
          const res = await fetch(url, { cache: "reload" });
          if (!res.ok) throw new Error("Precache failed: " + url);
          // Safari refuses redirected responses for navigations, so store a clean copy.
          const clean = res.redirected
            ? new Response(await res.blob(), { status: 200, headers: res.headers })
            : res;
          await cache.put(key, clean);
        }),
      );
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k.startsWith("dialed-") && k !== CACHE).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

function pageKey(url) {
  let p = url.pathname;
  if (p.endsWith("/index.html")) p = p.slice(0, -"index.html".length);
  else if (!p.endsWith("/") && !p.split("/").pop().includes(".")) p += "/";
  return p;
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Cache first: the app shell never needs the network once installed.
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      if (req.mode === "navigate") {
        const page = await cache.match(pageKey(url));
        if (page) return page;
        try {
          return await fetch(req);
        } catch {
          return (await cache.match("/")) || Response.error();
        }
      }
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;
      try {
        return await fetch(req);
      } catch {
        return Response.error();
      }
    })(),
  );
});
`;

await writeFile(path.join(OUT, "sw.js"), sw);
console.log(`Service worker: ${entries.length} files precached, version ${version}`);
